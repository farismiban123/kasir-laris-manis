    private void btnTambahBahanBakuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahBahanBakuActionPerformed
        try{
            int kuantitas = Integer.parseInt(fieldKuantitasBahan.getText());

            resepRepo.addResep(menuId, selectedBahanTableId, kuantitas);
            loadResepTable(); 
            
            fieldKuantitasBahan.setText("");
        }catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Input harga harus berupa angka!",
                    "Validasi Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnTambahBahanBakuActionPerformed

