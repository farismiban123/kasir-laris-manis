    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        if(selectedId == 0){
            javax.swing.JOptionPane.showMessageDialog(this, "Belum Pilih Barang!");
            TableBahanBaku.requestFocus();
            return;
        }
        
        bahanBakuRepo.deleteBahanBaku(selectedId);
        loadBahanBakuTable();
        selectedId = 0;
        fieldSelectedBahan.setText("");
    }//GEN-LAST:event_btnDeleteActionPerformed

