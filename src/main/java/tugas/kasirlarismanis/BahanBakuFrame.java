    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        if(selectedId == 0){
            javax.swing.JOptionPane.showMessageDialog(this, "Belum Pilih Barang!");
            fieldName.requestFocus();
            return;
        }
        
        String name = fieldName.getText();
        if(name.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "Nama Barang Tidak Boleh Kosong!");
            fieldName.requestFocus();
            return;
        }
        
        try{
            double price = Double.parseDouble(fieldHarga.getText());
            int stock = Integer.parseInt(fieldStok.getText());
            int batasMinimum = Integer.parseInt(fieldBatasMinimum.getText());

            bahanBakuRepo.updateBahanBaku(selectedId, name, price, stock, batasMinimum);
            loadBahanBakuTable(); 
            
            fieldName.setText("");
            fieldHarga.setText("");
            fieldStok.setText("");
            fieldBatasMinimum.setText("");
        }catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Input harga harus berupa angka!",
                    "Validasi Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditActionPerformed

