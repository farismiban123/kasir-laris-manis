    private void loadBahanBakuTable(){
        DefaultTableModel model = (DefaultTableModel) TableBahanBaku.getModel();
        model.setRowCount(0);
        List<BahanBaku> bahanBaku = bahanBakuRepo.getBahanBakuItems();
        for(BahanBaku bb : bahanBaku){
            model.addRow(new Object[]{bb.getId(), bb.getNama(), bb.getHargaSatuan(), bb.getStokTersedia(), bb.getBatasMinimum()});
        }
    }

