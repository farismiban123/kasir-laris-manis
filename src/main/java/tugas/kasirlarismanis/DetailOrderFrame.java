    private void loadMenuTable(){
        DefaultTableModel model = (DefaultTableModel) tableMenu.getModel();
        model.setRowCount(0);
        List<MenuModel> menu = menuRepo.getMenuItemsModel();
        for(MenuModel m : menu){
            model.addRow(new Object[]{m.getId(), m.getNama(), m.getKategori(), m.getHargaJual(), m.getStok()});
        }
    }
    
    private void loadDetailOrderTable(int orderId){
        DefaultTableModel model = (DefaultTableModel) tableDetailOrder.getModel();
        model.setRowCount(0);
        List<DetailOrderModel> detailOrder = detailOrderRepo.getDetailOrderItems(orderId);
        for(DetailOrderModel d : detailOrder){
            model.addRow(new Object[]{d.getId(), d.getNama(), d.getKuantitas(), d.getHargaSatuan(), d.getHargaTotal()});
        }
    }

