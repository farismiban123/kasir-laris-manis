    private void loadLaporanHarianTable(){
        DefaultTableModel model = (DefaultTableModel) tableLaporanHarian.getModel();
        model.setRowCount(0);
        List<LaporanHarian> laporanHarian = laporanHarianRepo.getLaporanHarianItems();
        for(LaporanHarian lh : laporanHarian){
            model.addRow(new Object[]{lh.getId(), lh.getTanggal(), lh.getJumlahPesanan(),lh.getPendapatan()});
        }
    }

