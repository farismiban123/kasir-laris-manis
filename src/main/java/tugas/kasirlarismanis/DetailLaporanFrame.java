    public DetailLaporanFrame(int laporanId) {
        initComponents();
        loadOrdersTable(laporanId);
        
        fieldIDLaporan.setText(Integer.toString(laporanId));
        this.laporanId = laporanId;
        
        tableOrders.getSelectionModel().addListSelectionListener(new ListSelectionListener() {
            @Override
            public void valueChanged(ListSelectionEvent event) {
                if (!event.getValueIsAdjusting()) {
                    int selectedRow = tableOrders.getSelectedRow();

                    if (selectedRow != -1) {
                        selectedId = (int) tableOrders.getValueAt(selectedRow, 0);
                        fieldSelected.setText(String.valueOf(tableOrders.getValueAt(selectedRow, 0)));
                    }
                }
            }
        });
    }
    
    private void loadOrdersTable(int idLaporan){
        DefaultTableModel model = (DefaultTableModel) tableOrders.getModel();
        model.setRowCount(0);
        List<OrderModel> orders = orderRepo.getOrdersLaporan(idLaporan);
        for(OrderModel o : orders){
            model.addRow(new Object[]{o.getId(), o.getNomorAntrean(), o.getNama(), o.getJenisOrder(), o.getTanggalTransaksi(), o.getTotalHarga()});
        }
    }

