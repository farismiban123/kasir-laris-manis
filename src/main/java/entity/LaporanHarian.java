package entity;

import java.time.LocalDate;

/**
 *
 * @author Faris M Rabbani
 */
public class LaporanHarian {
    private int id, jumlahPesanan;
    private double pendapatan;
    private LocalDate tanggal;

    public LaporanHarian(int id, int jumlahPesanan, double pendapatan, LocalDate tanggal){
        this.id = id;
        this.jumlahPesanan = jumlahPesanan;
        this.pendapatan = pendapatan;
        this.tanggal = tanggal;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public int getJumlahPesanan() {
        return jumlahPesanan;
    }

    public void setJumlahPesanan(int jumlahPesanan) {
        this.jumlahPesanan = jumlahPesanan;
    }

    public double getPendapatan() {
        return pendapatan;
    }

    public void setPendapatan(double pendapatan) {
        this.pendapatan = pendapatan;
    }

    public LocalDate getTanggal() {
        return tanggal;
    }

    public void setTanggal(LocalDate tanggal) {
        this.tanggal = tanggal;
    }
}
