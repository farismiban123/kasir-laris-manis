package entity;

import java.time.LocalDateTime;

/**
 *
 * @author Faris M Rabbani
 */
public class Order {
    private int id, nomorAntrean;
    private String nama;
    private LocalDateTime tanggalTransaksi;
    private double totalHarga;

    public Order(int id, int nomorAntrean, double totalHarga, LocalDateTime tanggalTransaksi){
        this.id = id;
        this.nomorAntrean = nomorAntrean;
        this.totalHarga = totalHarga;
        this.tanggalTransaksi = tanggalTransaksi;

        nama = "";
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getNama() {
        return nama;
    }

    public void setNama(String nama) {
        this.nama = nama;
    }

    public int getNomorAntrean() {
        return nomorAntrean;
    }

    public void setNomorAntrean(int nomorAntrean) {
        this.nomorAntrean = nomorAntrean;
    }

    public double getTotalHarga() {
        return totalHarga;
    }

    public void setTotalHarga(double totalHarga) {
        this.totalHarga = totalHarga;
    }
    
    public LocalDateTime getTanggalTransaksi() {
        return tanggalTransaksi;
    }

    public void setTanggalTransaksi(LocalDateTime tanggalTransaksi) {
        this.tanggalTransaksi = tanggalTransaksi;
    }
}
